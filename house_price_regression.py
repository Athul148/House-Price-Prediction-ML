import numpy as np
import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt

df=pd.read_csv('/content/house_price_regression.csv')
df

df.isna().sum()

df.dtypes

from sklearn.preprocessing import LabelEncoder
lb=LabelEncoder()
df['house_type']=lb.fit_transform(df['house_type'])

df['area_sqft'].hist()

df.boxplot(column=['area_sqft'])

df.boxplot(column=['num_bedrooms'])

df['age_years'].hist()

df.boxplot(column=['age_years'])

df['distance_to_city_km'].hist()

df.boxplot(column=['distance_to_city_km'])

df['crime_rate_index'].hist()

df.boxplot(column=['crime_rate_index'])

df['area_sqft'].fillna(df['area_sqft'].median(),inplace=True)
df['num_bedrooms'].fillna(df['num_bedrooms'].mean(),inplace=True)
df['age_years'].fillna(df['age_years'].mean(),inplace=True)
df['distance_to_city_km'].fillna(df['distance_to_city_km'].median(),inplace=True)
df['crime_rate_index'].fillna(df['crime_rate_index'].median(),inplace=True)

df.dtypes

df['num_bedrooms']=df['num_bedrooms'].astype(int)

x=df.drop(columns=['price_usd'])
y=df['price_usd']

#train test split

from sklearn.model_selection import train_test_split
x_train,x_test,y_train,y_test=train_test_split(x,y,test_size=0.2,random_state=42)

#model

from sklearn.linear_model import LinearRegression
lr=LinearRegression()
lr.fit(x_train,y_train)
y_pred=lr.predict(x_test)

from sklearn.metrics import r2_score,mean_absolute_percentage_error
r2=r2_score(y_test,y_pred)
mape=mean_absolute_percentage_error(y_test,y_pred)

r2

mape

import pickle
pickle.dump(lr,open('reg_model.save','wb'))
pickle.dump(lb,open('label_encoder.save','wb'))